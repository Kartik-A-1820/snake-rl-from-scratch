# Records what is actually installed on this machine into ENVIRONMENT.md. Installs nothing.
import importlib
import json
import platform
import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252


def run(cmd):
    exe = shutil.which(cmd[0])
    if not exe:
        return None
    try:
        return subprocess.run([exe, *cmd[1:]], capture_output=True, text=True, timeout=30).stdout.strip()
    except Exception as e:  # report, don't crash: this script is a diagnostic
        return f"error: {e}"


def version(mod):
    try:
        return importlib.import_module(mod).__version__
    except Exception:
        return None


r = {"when": datetime.now().isoformat(timespec="seconds"), "python": sys.version.split()[0],
     "python_exe": sys.executable, "platform": platform.platform()}
smi = run(["nvidia-smi"])
r["nvidia_smi"] = smi
# Older drivers print "Driver Version: X ... CUDA Version: Y"; newer ones print "KMD Version: X ... CUDA UMD Version: Y".
m = re.search(r"(?:Driver|KMD) Version:\s*([\d.]+).*?CUDA(?: UMD)? Version:\s*([\d.]+)", smi or "", re.S)
r["driver"], r["driver_max_cuda"] = (m.group(1), m.group(2)) if m else (None, None)

try:
    import torch
    r["torch"] = torch.__version__
    r["torch_cuda"] = torch.version.cuda
    r["cuda_available"] = torch.cuda.is_available()
    r["cudnn"] = torch.backends.cudnn.version() if r["cuda_available"] else None
    if r["cuda_available"]:
        p = torch.cuda.get_device_properties(0)
        r["gpu"] = {"name": p.name, "vram_gib": round(p.total_memory / 2**30, 2), "sm": f"{p.major}.{p.minor}",
                    "arch_list": torch.cuda.get_arch_list()}
        x = torch.randn(256, 256, device="cuda")
        r["cuda_matmul_ok"] = bool(torch.isfinite(x @ x).all())
except Exception as e:
    r["torch"] = None
    r["torch_error"] = str(e)

r["packages"] = {k: version(k) for k in ("numpy", "gymnasium", "matplotlib", "onnx", "onnxruntime", "onnxscript", "pytest")}
r["node"] = run(["node", "--version"])
r["pandoc"] = (run(["pandoc", "--version"]) or "").split("\n")[0] or None

advice = []
if not r.get("torch"):
    advice.append("PyTorch is not importable from this Python.")
elif not r.get("torch_cuda"):
    # GTX 1650 Ti is Turing (sm_75): supported by the cu130 (stable) and cu126 (legacy) builds.
    tag = "cu130" if r["driver_max_cuda"] and float(r["driver_max_cuda"]) >= 13.0 else "cu126"
    advice.append("Installed torch is a CPU-only build. Matching CUDA wheel (NOT run automatically, ~2.5 GB):\n"
                  f"    python -m pip install --upgrade torch --index-url https://download.pytorch.org/whl/{tag}")
elif not r.get("cuda_available"):
    advice.append(f"torch was built for CUDA {r['torch_cuda']} but no GPU is usable: check the driver "
                  f"(nvidia-smi says it supports up to CUDA {r['driver_max_cuda']}).")
missing = [k for k, v in r["packages"].items() if v is None]
if missing:
    advice.append("Missing small packages: " + " ".join(missing) + "  →  .\\run.ps1 setup installs them into the project .venv")
if not r["node"]:
    advice.append("Node.js not found: needed for the JS↔Python parity test and tools/train_tabular.js.")
if not r["pandoc"]:
    advice.append("pandoc not found: needed to build the .docx notes (winget install --id JohnMacFarlane.Pandoc).")
r["advice"] = advice

(ROOT / "results").mkdir(exist_ok=True)
(ROOT / "results" / "env_report.json").write_text(json.dumps(r, indent=1))
gpu = r.get("gpu") or {}
md = f"""# Environment (auto-generated by python/check_env.py, {r['when']})

| item | value |
|---|---|
| OS | {r['platform']} |
| Python | {r['python']} (`{r['python_exe']}`) |
| NVIDIA driver | {r['driver']} (supports CUDA ≤ {r['driver_max_cuda']}) |
| torch | {r.get('torch')} |
| torch.version.cuda | {r.get('torch_cuda')} |
| torch.cuda.is_available() | {r.get('cuda_available')} |
| GPU | {gpu.get('name')} · {gpu.get('vram_gib')} GiB · sm_{gpu.get('sm', '').replace('.', '')} |
| cuDNN | {r.get('cudnn')} |
| node | {r['node']} |
| pandoc | {r['pandoc']} |
| packages | {', '.join(f'{k} {v}' for k, v in r['packages'].items())} |

## Action needed
{chr(10).join('- ' + a for a in advice) if advice else 'Nothing: ready to train on the GPU.'}

<details><summary>nvidia-smi</summary>

```
{smi}
```
</details>
"""
(ROOT / "ENVIRONMENT.md").write_text(md, encoding="utf-8")
print(md)
