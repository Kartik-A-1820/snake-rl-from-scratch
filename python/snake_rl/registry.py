# Model registry: one isolated folder per algorithm, and a registry the game loads with plain <script> tags.
#
#   models/<algo_id>/best.json          game format (layers + test vectors, or tabular Q-table)
#   models/<algo_id>/best.onnx          ONNX Runtime (DQN nets only)
#   models/<algo_id>/best.pt            PyTorch checkpoint (DQN nets only)
#   models/<algo_id>/meta.json          name, tryout, board size, params, test stats, training cost, date, notes link
#   models/<algo_id>/best.weights.js    window.SNAKE_MODELS['<algo_id>'] = {...best.json...}   (lazy-loaded by the game)
#   models/registry.js                  window.SNAKE_REGISTRY = [ {id, ...meta, weights: '<algo_id>/best.weights.js'}, ... ]
#
# Why scripts and not fetch(): the game is opened by double-clicking index.html (file://), where browsers block
# fetch() of local JSON. <script src> is allowed. publish() regenerates registry.js every time, so the UI is
# current after every tryout with no manual step.
import datetime
import json
import shutil
from pathlib import Path

from .core import SnakeGame
from .features import basic_index

ROOT = Path(__file__).resolve().parents[2]
MODELS = ROOT / "models"
TEST_SEEDS = list(range(100000, 100500))   # held-out test seeds (same as tryouts 01 and 02)
VAL_SEEDS = list(range(200000, 200200))    # used to decide whether a new model replaces the registered one


def load_meta(algo_id):
    p = MODELS / algo_id / "meta.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def should_replace(algo_id, new_score):
    """True when nothing is registered yet or new_score (validation mean) beats the registered one."""
    old = load_meta(algo_id)
    if old is None or old.get("provisional") or old.get("select_score") is None:
        return True   # nothing registered, or only an "in training" snapshot: the finished run always replaces it
    return new_score > old["select_score"]


def rebuild_registry():
    entries = []
    for meta_path in sorted(MODELS.glob("*/meta.json")):
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        meta["weights"] = f"{meta_path.parent.name}/best.weights.js"
        entries.append(meta)
    text = ("// generated by python/snake_rl/registry.py: do not edit. Loaded by game/index.html via <script>.\n"
            "window.SNAKE_REGISTRY = " + json.dumps(entries, indent=1) + ";\n")
    (MODELS / "registry.js").write_text(text, encoding="utf-8")
    return entries


def publish(algo_id, model, meta, pt_src=None, onnx_src=None):
    """Write models/<algo_id>/ from an in-memory game-format model dict + metadata, then rebuild registry.js."""
    d = MODELS / algo_id
    d.mkdir(parents=True, exist_ok=True)
    jtxt = json.dumps(model, separators=(",", ":"))
    (d / "best.json").write_text(jtxt, encoding="utf-8")
    (d / "best.weights.js").write_text(
        "(window.SNAKE_MODELS = window.SNAKE_MODELS || {})[" + json.dumps(algo_id) + "] = " + jtxt + ";\n", encoding="utf-8")
    if pt_src:
        shutil.copyfile(pt_src, d / "best.pt")
    if onnx_src:
        shutil.copyfile(onnx_src, d / "best.onnx")
    meta = dict(meta, id=algo_id, date=datetime.datetime.now().isoformat(timespec="seconds"),
                json_mb=round((d / "best.json").stat().st_size / 1e6, 3))
    (d / "meta.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    rebuild_registry()
    return d


def summarize_scores(scores, causes):
    s = sorted(scores)
    n = len(s)
    pct = lambda p: s[min(n - 1, int(p * n))]
    mean = sum(s) / n
    return {"n": n, "mean": mean, "std": (sum((x - mean) ** 2 for x in s) / n) ** 0.5, "median": pct(0.5), "p10": pct(0.1), "p90": pct(0.9), "max": s[-1],
            "wins": int(causes.get("win", 0)), "causes": causes}


def eval_tabular(model, size=12, seeds=TEST_SEEDS):
    """Greedy evaluation of a tabular model with the Python engine (same rules and seeds as the JS game)."""
    q = model["q"]
    scores, causes = [], {}
    for seed in seeds:
        g = SnakeGame(size, size, seed=seed)
        while not g.done:
            row = q.get(str(basic_index(g)), [0, 0, 0])
            g.step(max(range(3), key=lambda i: (row[i], -i)))
        scores.append(g.score)
        causes[g.cause] = causes.get(g.cause, 0) + 1
    return summarize_scores(scores, causes)
