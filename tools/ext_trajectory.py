# The 12x12 trajectory table: every checkpoint evaluation (greedy, 500 held-out games) of the 24 M-step stage and of the extended run,
# straight from the runs' per-epoch logs. Writes docs/12x12_trajectory.md and prints it.
#   python tools/ext_trajectory.py
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def evals(run):
    f = ROOT / "results" / "phase4_ppo" / run / "metrics.jsonl"
    if not f.exists():
        return []
    return [json.loads(line)["checkpoint"] for line in f.read_text(encoding="utf-8").splitlines() if line.strip() and '"checkpoint"' in line]


def main():
    cells = 141
    stage, ext = evals("t05_12x12_win6_scratch"), evals("t05_12x12_ext")
    offset = stage[-1]["env_steps"] if stage else 0
    rows = ["| Run | Steps in the run | Total 12x12 steps | Mean score | Mean fill | Median | p90 | Best game | Wins / 500 | Deaths wall / self / timeout |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for run, cps, off in (("24 M-step stage", stage, 0), ("extended run", ext, offset)):
        for c in cps:
            t = c["test"]
            d = t["causes"]
            rows.append(f"| {run} | {c['env_steps'] / 1e6:.1f} M | {(c['env_steps'] + off) / 1e6:.1f} M | {t['mean']:.1f} | {100 * t['mean'] / cells:.0f}% | {t['median']:.0f} | "
                        f"{t['p90']:.0f} | {t['max']} | **{t['wins']}** ({100 * t['wins'] / t.get('n', 500):.1f}%) | {d.get('wall', 0)} / {d.get('self', 0)} / {d.get('timeout', 0)} |")
    out = "# 12×12 trajectory (greedy play, 500 held-out games per evaluation)\n\nGenerated by `tools/ext_trajectory.py` from `results/phase4_ppo/*/metrics.jsonl`.\n\n" + "\n".join(rows) + "\n"
    (ROOT / "docs" / "12x12_trajectory.md").write_text(out, encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
